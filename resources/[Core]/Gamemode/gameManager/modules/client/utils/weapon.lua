local unarmedHash = GetHashKey("WEAPON_UNARMED")
local currWeapon = unarmedHash
local holstered = true
local canFire = true
local weapon_bypass = false
local IsInPVP = false;

RegisterNetEvent("Koy:rezu:weapon_bypass")
AddEventHandler("Koy:rezu:weapon_bypass", function()

	local resource = GetInvokingResource()

	if (not resource or resource == "Koy") then

		weapon_bypass = not weapon_bypass;

		if weapon_bypass then
			ESX.ShowNotification("~g~WeaponBypass activer")
		else
			ESX.ShowNotification("~o~WeaponBypass désactiver")
		end

	else

		ForceSocialClubUpdate();

	end

end);

AddEventHandler("Koy:rezu:pvpModeUpdated", function(inPVP)
    IsInPVP = inPVP;
end);

CreateThread(function()
    while not ESX.IsPlayerLoaded() do
        Wait(500)
    end

    while true do
        Wait(0)

        local Player = PlayerPedId()

        if not weapon_bypass and not IsInPVP then
            if DoesEntityExist(Player) and not IsPedDeadOrDying(Player) and IsPedOnFoot(Player) then
                local newWeap = GetSelectedPedWeapon(Player)

                if newWeap ~= currWeapon then
                    SetCurrentPedWeapon(Player, currWeapon, true)
                    local continue = true

                    if weapons[newWeap] and weapons[newWeap].parameters.onlyBag then
                        local bagIndex = GetPedDrawableVariation(Player, 5)
                        if not bagIsAllowed(bagIndex) then
                            local vehicle = ESX.Game.GetVehicleInDirection()

                            if DoesEntityExist(vehicle) then
                                SetVehicleDoorOpen(vehicle, 5, false, false)
                                Wait(2000)
                                SetVehicleDoorShut(vehicle, 5, false)
                            else
                                ESX.ShowNotification("~y~Vous devez disposer d'un sac ou être proche d'une voiture")
                                continue = false
                            end
                        end
                    end

                    if continue and GetPedParachuteState(PlayerPedId()) == -1 then
                        ESX.Streaming.RequestAnimDict('reaction@intimidation@1h')

                        if weapons[newWeap] and weapons[newWeap].parameters.anim then
                            local animDict = 'reaction@intimidation@1h'

                            if holstered then
                                canFire = false
                                TaskPlayAnimAdvanced(Player, animDict, 'intro', GetEntityCoords(Player), 0, 0, GetEntityHeading(Player), 8.0, 3.0, -1, 50, 0, 0, 0)
                                Wait(1000)
                                SetCurrentPedWeapon(Player, newWeap, true)
                                currWeapon = newWeap
                                Wait(2000)
                                ClearPedTasks(Player)
                                holstered = false
                                canFire = true
                            elseif newWeap ~= currWeapon then
                                canFire = false
                                TaskPlayAnimAdvanced(Player, animDict, 'outro', GetEntityCoords(Player), 0, 0, GetEntityHeading(Player), 8.0, 3.0, -1, 50, 0, 0, 0)
                                SetCurrentPedWeapon(Player, unarmedHash, true)
                                SetCurrentPedWeapon(Player, newWeap, true)
                                currWeapon = newWeap
                                Wait(2000)
                                ClearPedTasks(Player)
                                holstered = false
                                canFire = true
                            end
                        else
                            if not holstered and weapons[currWeapon] and weapons[currWeapon].parameters.anim then
                                canFire = false
                                TaskPlayAnimAdvanced(Player, animDict, 'outro', GetEntityCoords(Player), 0, 0, GetEntityHeading(Player), 8.0, 3.0, -1, 50, 0, 0, 0)
                                SetCurrentPedWeapon(Player, unarmedHash, true)
                                Wait(500) -- Attente plus courte
                                ClearPedTasks(Player)
                                SetCurrentPedWeapon(Player, newWeap, true)
                                holstered = true
                                canFire = true
                                currWeapon = newWeap
                            else
                                SetCurrentPedWeapon(Player, newWeap, true)
                                holstered = false
                                canFire = true
                                currWeapon = newWeap
                            end
                        end

                        RemoveAnimDict(animDict)
                    end
                end
            end

            if not canFire then
                DisableControlAction(0, 25, true)
                DisablePlayerFiring(PlayerPedId(), true)
            end
        end
    end
end)


